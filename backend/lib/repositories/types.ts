export interface Player {
  playerId: string;
  userId?: string;
  /**
   * Denormalized copy of "this player's Cognito user is in the Wrestler
   * group". Public read paths (standings, roster pickers) are unauthenticated
   * and cannot call Cognito per request, so the flag is maintained by
   * postConfirmation / updateUserRole and backfilled by the sync-roles
   * endpoint.
   *
   * Tri-state on purpose:
   *   true      — confirmed Wrestler, always shown
   *   false     — confirmed non-Wrestler (or no linked account), hidden
   *   undefined — never synced; treated as shown, so deploying this filter
   *               cannot blank the roster before the backfill has run.
   */
  hasWrestlerRole?: boolean;
  /**
   * Set when the player is deleted. The row stays so history keeps the name,
   * but it reads as missing through every repository method except the
   * `...WithDeleted` name lookups.
   */
  deletedAt?: string;
  name: string;
  currentWrestler: string;
  alternateWrestler?: string;
  // FK to Wrestlers table (P1). The denormalized `currentWrestler` / `alternateWrestler`
  // string fields remain as a display cache so existing read paths (Standings, Dashboard,
  // PublicProfile) stay untouched.
  currentWrestlerId?: string;
  alternateWrestlerId?: string;
  wins: number;
  losses: number;
  draws: number;
  imageUrl?: string;
  psnId?: string;
  divisionId?: string;
  /**
   * When the player joined `divisionId`. Set whenever the division changes;
   * older rows were backfilled to `createdAt`. Progression tracks with
   * `windowMode: 'sinceJoinedDivision'` count activity from this instant.
   */
  divisionJoinedAt?: string;
  /**
   * The progression epoch (PRL-01): when this player's promotion, relegation
   * and call-up goals last started over (a division move or a GM reset).
   * Every progression track ignores activity from before it. Absent on rows
   * written before the field shipped; readers fall back to `divisionJoinedAt`.
   * Never touches win/loss/draw totals or season standings.
   */
  progressionEpochAt?: string;
  companyId?: string;
  stableId?: string;
  tagTeamId?: string;
  alignment?: 'face' | 'heel' | 'neutral';
  mainOverall?: number;
  /** When true, this wrestler may submit videos via /my-videos. Admin-managed. */
  canUploadVideos?: boolean;
  /** Free-text intro shown on the profile and read out on commentary. */
  bio?: string;
  /** Up to MAX_MOVES signature moves; see lib/movesets.ts for the limits. */
  signatures?: WrestlerMove[];
  /** Up to MAX_MOVES finishers; see lib/movesets.ts for the limits. */
  finishers?: WrestlerMove[];

  // BLD-03
  /**
   * The player's saved build. Absent until the first save; readers fall back
   * to `defaultBuild()`. Move levels live on `signatures` / `finishers`.
   */
  build?: WrestlerBuild;

  /**
   * Discipline fields. These are not on `PlayerPatch`: write them only through
   * `players.updateDiscipline`, and read them only through `lib/discipline.ts`.
   */
  strikes?: PlayerStrike[];
  deactivations?: PlayerDeactivation[];
  /** Present only while deactivated. Copy of the open PlayerDeactivation record. */
  deactivatedAt?: string;
  /** Optimistic lock for discipline writes. Absent reads as 0. */
  disciplineVersion?: number;
  /** toSignupGuardKey(email), stored at any strike that blocks or deactivates. Only used while isSignupBlocked. */
  signupGuardKey?: string;
  /**
   * ECO-02: cached sum of the player's ledger entries; missing = 0, may be
   * negative. Written only by `tx.postLedgerEntry`; never on `PlayerPatch`.
   */
  balance?: number;

  // ECO-08
  /**
   * Shop effects the player bought and that have not been used up yet. Written
   * only through `tx.postLedgerEntry({ appendPlayerEffects })`, so the
   * purchase and its effect commit together; never on `PlayerPatch`. Private
   * to staff and the player.
   */
  effects?: PlayerEffect[];

  /**
   * ECO-03: the player's one active contract, denormalized so free-agent
   * checks need no Contracts query. Not on `PlayerPatch`: write it only
   * through `tx.setPlayerActiveContract` / `tx.clearPlayerActiveContract`.
   */
  activeContractId?: string;

  // INJ-03
  /**
   * Stamina, 0 to the tunable maximum. Missing means full (`currentStamina`
   * in lib/injuries). Private to staff and the player. Not on `PlayerPatch`:
   * write it only through `tx.updatePlayerCondition`.
   */
  stamina?: number;
  /**
   * Copy of the open row in the Injuries table, or absent. The player counts
   * as injured while `returnsAt` is in the future (`isInjured`). Not on
   * `PlayerPatch`: write it only through `tx.updatePlayerCondition`.
   */
  currentInjury?: CurrentInjury;

  createdAt: string;
  updatedAt: string;
}

