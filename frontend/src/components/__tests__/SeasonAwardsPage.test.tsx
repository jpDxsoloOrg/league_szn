import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter } from 'react-router-dom';

const { mockGetSeasons, mockGetAwards } = vi.hoisted(() => ({
  mockGetSeasons: vi.fn(),
  mockGetAwards: vi.fn(),
}));

vi.mock('../../services/api', () => ({
  seasonsApi: { getAll: mockGetSeasons },
  seasonAwardsApi: { getAll: mockGetAwards },
}));

vi.mock('react-i18next', () => ({
  useTranslation: () => ({ t: (key: string) => key }),
}));

import SeasonAwardsPage from '../SeasonAwardsPage';

const seasons = [
  { seasonId: 's1', name: 'Season 1', startDate: '2024-01-01', status: 'completed', createdAt: '2024-01-01', updatedAt: '2024-01-01' },
  { seasonId: 's2', name: 'Season 2', startDate: '2024-06-01', status: 'active', createdAt: '2024-06-01', updatedAt: '2024-06-01' },
];

const mvp = {
  awardId: 'a1',
  seasonId: 's2',
  name: 'MVP',
  awardType: 'mvp',
  playerId: 'p1',
  playerName: 'John Cena',
  value: '25 wins',
  createdAt: '2024-06-01',
  autoGenerated: true,
};

function renderPage() {
  return render(
    <MemoryRouter>
      <SeasonAwardsPage />
    </MemoryRouter>,
  );
}

describe('SeasonAwardsPage', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mockGetSeasons.mockResolvedValue(seasons);
    mockGetAwards.mockResolvedValue({ autoAwards: [mvp], customAwards: [] });
  });

  it('opens on the active season and links the winner', async () => {
    renderPage();

    expect(await screen.findByRole('link', { name: 'John Cena' })).toHaveAttribute('href', '/player/p1');
    expect(screen.getByText('25 wins')).toBeInTheDocument();
    expect(mockGetAwards).toHaveBeenCalledWith('s2', expect.any(AbortSignal));
  });

  it('loads awards for the chosen season', async () => {
    const user = userEvent.setup();
    renderPage();

    await user.click(await screen.findByRole('combobox', { name: 'standings.season' }));
    await user.click(await screen.findByRole('option', { name: 'Season 1' }));

    await waitFor(() => {
      expect(mockGetAwards).toHaveBeenCalledWith('s1', expect.any(AbortSignal));
    });
  });

  it('shows empty states for no awards and no seasons', async () => {
    mockGetAwards.mockResolvedValue({ autoAwards: [], customAwards: [] });
    const { unmount } = renderPage();
    expect(await screen.findByText('seasonAwards.noAwards')).toBeInTheDocument();
    unmount();

    mockGetSeasons.mockResolvedValue([]);
    renderPage();
    expect(await screen.findByText('seasonAwards.noSeasons')).toBeInTheDocument();
  });

  it('offers a retry when awards fail to load', async () => {
    const user = userEvent.setup();
    mockGetAwards.mockRejectedValueOnce(new Error('Server down'));
    renderPage();

    await user.click(await screen.findByRole('button', { name: 'common.retry' }));

    expect(await screen.findByText('John Cena')).toBeInTheDocument();
  });
});
