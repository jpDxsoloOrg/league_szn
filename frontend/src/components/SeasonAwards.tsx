import { useEffect, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { Link } from 'react-router-dom';
import { BarChart3, Dumbbell, Flame, Medal, Star, Trophy } from 'lucide-react';
import type { LucideIcon } from 'lucide-react';
import { seasonAwardsApi } from '../services/api';
import type { SeasonAwardsResponse } from '../services/api';
import type { Season, SeasonAward } from '../types';
import Badge from './ui/Badge';
import EmptyState from './ui/EmptyState';
import Skeleton from './ui/Skeleton';
import './SeasonAwards.css';

interface SeasonAwardsProps {
  season: Season;
}

const AWARD_ICONS: Record<string, LucideIcon> = {
  mvp: Trophy,
  longest_win_streak: Flame,
  iron_man: Dumbbell,
  best_win_pct: BarChart3,
  most_title_defenses: Medal,
};

function AwardItem({ award }: { award: SeasonAward & { autoGenerated?: boolean } }) {
  const { t } = useTranslation();
  const Icon = AWARD_ICONS[award.awardType] ?? Star;
  const playerName = award.playerName || t('common.unknown');

  return (
    <li className="season-award">
      <span className="season-award__icon"><Icon aria-hidden="true" size={22} /></span>
      <div className="season-award__body">
        <h3 className="season-award__name">{award.name}</h3>
        {award.playerId
          ? <Link to={`/player/${award.playerId}`} className="season-award__player">{playerName}</Link>
          : <span className="season-award__player">{playerName}</span>}
        {award.description && <p className="season-award__description">{award.description}</p>}
      </div>
      <div className="season-award__side">
        {award.value && <span className="season-award__value">{award.value}</span>}
        {award.autoGenerated && <Badge>{t('seasonAwards.auto')}</Badge>}
      </div>
    </li>
  );
}

export default function SeasonAwards({ season }: SeasonAwardsProps) {
  const { t } = useTranslation();
  const [data, setData] = useState<SeasonAwardsResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [reloadCount, setReloadCount] = useState(0);

  useEffect(() => {
    const abortController = new AbortController();

    const fetchAwards = async () => {
      try {
        setLoading(true);
        setError(null);
        const result = await seasonAwardsApi.getAll(season.seasonId, abortController.signal);
        if (!abortController.signal.aborted) setData(result);
      } catch (err) {
        if (err instanceof Error && err.name !== 'AbortError') {
          setError(err.message);
        }
      } finally {
        if (!abortController.signal.aborted) setLoading(false);
      }
    };

    fetchAwards();
    return () => abortController.abort();
  }, [season.seasonId, reloadCount]);

  if (loading) return <Skeleton variant="block" count={3} />;

  if (error !== null) {
    return (
      <EmptyState
        title={t('common.error')}
        description={error || t('seasonAwards.loadFailed')}
        actionLabel={t('common.retry')}
        onAction={() => setReloadCount((count) => count + 1)}
      />
    );
  }

  if (!data || (data.autoAwards.length === 0 && data.customAwards.length === 0)) {
    return <EmptyState title={t('seasonAwards.emptyTitle')} description={t('seasonAwards.noAwards')} />;
  }

  return (
    <div className="season-awards">
      {data.autoAwards.length > 0 && (
        <section>
          <h2 className="season-awards__heading">{t('seasonAwards.autoAwards')}</h2>
          <ul className="season-awards__list">
            {data.autoAwards.map((award) => <AwardItem key={award.awardId} award={award} />)}
          </ul>
        </section>
      )}

      {data.customAwards.length > 0 && (
        <section>
          <h2 className="season-awards__heading">{t('seasonAwards.customAwards')}</h2>
          <ul className="season-awards__list">
            {data.customAwards.map((award) => <AwardItem key={award.awardId} award={award} />)}
          </ul>
        </section>
      )}
    </div>
  );
}
